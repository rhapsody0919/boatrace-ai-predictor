let failures = 0;
function check(label, pass, detail = "") {
  if (pass) console.log(`[OK] ${label}`);
  else {
    failures++;
    console.error(`[NG] ${label}${detail ? ` (${detail})` : ""}`);
  }
}
function throwsWith(fn, pattern) {
  try {
    fn();
    return false;
  } catch (e) {
    return pattern.test(e.message);
  }
}

