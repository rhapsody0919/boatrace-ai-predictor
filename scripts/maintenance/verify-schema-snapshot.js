/**
 * verify-schema-snapshot.js - 本番スキーマの写し（ADR-0102）の取得の問い合わせと組み立て（scripts/lib/schemaSnapshot.js）の検証。
 * 本番 DB には接続しない。
 *
 * 確認すること:
 *   (a) scripts/db/schema-snapshot/*.sql が ro-query の受け付ける1文で、PGlite の Postgres で実行できる
 *       （runReadOnlyQuery で READ ONLY・ROLLBACK のまま）。小さなスキーマから表・ビュー・列・関数・ポリシー・
 *       制約（外部キーの列の対応）・索引・トリガー・権限（列単位・PUBLIC・既定の権限の public と全体）を正しく組み立てる。
 *       拡張の作った関数は入らない。ALTER FUNCTION … SET search_path が config と定義に出る。
 *       問い合わせの行の並びを崩しても同じ出力になる
 *   (b) 組み立ての失敗: 打ち切り（truncated）・問い合わせの欠け・知らない記号・一覧に無い表の子・
 *       鍵らしい文字列（JWT・sb_secret_・Slack の Webhook・URL の資格情報）・search_path 等以外の関数の設定
 *   (c) 台帳（APPLIED.md）の読み方: ファイルの名前を単位にした鮮度の判定（同じ番号の片方・013b・後で行が足されたファイル）
 *   (d) コミット済みの docs/reference/schema-snapshot.json: 形・件数の整合・名前の順・整形のまま（serializeSnapshot で
 *       書き直しても変わらない）。base（--base、既定 origin/master）の写しより前の取得に戻っていない。
 *       古さでは落とさない（session-start-check が出す）
 *
 * 実行: npm run verify:schema-snapshot（@electric-sql/pglite は devDependency）
 */
