/**
 * verify-schema-snapshot.js - 本番スキーマの写し（ADR-0102）の取得の問い合わせと組み立て（scripts/lib/schemaSnapshot.js）の検証。
 * 本番 DB には接続しない。
 *
 * 確認すること:
 *   (a) scripts/db/schema-snapshot/*.sql が ro-query の受け付ける1文で、PGlite の Postgres で実行できる
 *       （runReadOnlyQuery で READ ONLY・ROLLBACK のまま）。小さなスキーマから表・ビュー・列・関数・ポリシー・
 *       制約・索引・権限（列単位・PUBLIC・既定の権限）を正しく組み立てる。拡張の作った関数は入らない。
 *       ALTER FUNCTION … SET search_path が config と定義に出る
 *   (b) 組み立ての失敗: 打ち切り（truncated）・問い合わせの欠け・知らない記号・一覧に無い表の子・鍵らしい文字列
 *   (c) 台帳（APPLIED.md）の読み方: appliedThrough・pendingAtCapture（欠番・行の無い番号を含む）と鮮度の判定
 *   (d) コミット済みの docs/reference/schema-snapshot.json: 形・件数の整合・名前の順・組み立ての出力のままか
 *       （serializeSnapshot で書き直しても変わらない＝手で書き換えていない）。古さでは落とさない（session-start-check が出す）
 *
 * 実行: npm run verify:schema-snapshot（@electric-sql/pglite は devDependency）
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PGlite } from "@electric-sql/pglite";
import {
  checkReadStatement,
  runReadOnlyQuery,
  MAX_ROW_LIMIT,
} from "../lib/roQuery.js";
import {
  SNAPSHOT_FILE,
  SNAPSHOT_FORMAT,
  SNAPSHOT_QUERIES,
  appliedLedgerState,
  buildSnapshot,
  serializeSnapshot,
  snapshotFreshness,
} from "../lib/schemaSnapshot.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "../..");
const QUERY_DIR = path.join(ROOT, "scripts/db/schema-snapshot");

let failures = 0;
function check(label, pass, detail = "") {
  if (pass) console.log(`[OK] ${label}`);
  else {
    failures++;
    console.error(`[NG] ${label}${detail ? ` (${detail})` : ""}`);
  }
}
function throwsWith(fn, pattern) {
  try {
    fn();
    return false;
  } catch (e) {
    return pattern.test(e.message);
  }
}

const LEDGER = [
  "| 番号 | ファイル | 状況 | 内容 |",
  "|---|---|---|---|",
  "| 001 | 001_a.sql | 適用済み | a |",
  "| 002 | 002_b.sql | 未適用（案） | b |",
  "| 004 | 004_d.sql | 適用済み（2026-10-27） | d |",
  "| 005 | 005_e.sql | 廃止（適用しない） | e |",
  "| 006 | 006_f.sql | 適用済み | f |",
  "| 008 | 008_h.sql | 未適用 | h |",
  "| （番号なし） | x.sql | 適用済み | x |",
].join("\n");

// ---------------------------------------------------------------------------
// (a) PGlite で問い合わせを実行して組み立てる
// ---------------------------------------------------------------------------
const FIXTURE_SQL = `
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN BYPASSRLS;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public GRANT SELECT ON TABLES TO service_role;

CREATE TABLE public.venues (code text PRIMARY KEY, name text NOT NULL);
CREATE TABLE public.races (
  race_id text PRIMARY KEY,
  venue_code text NOT NULL REFERENCES public.venues(code) ON DELETE CASCADE,
  race_number int NOT NULL CHECK (race_number BETWEEN 1 AND 12),
  seq bigint GENERATED BY DEFAULT AS IDENTITY,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (venue_code, race_number)
);
COMMENT ON TABLE public.races IS '1行1レース';
COMMENT ON COLUMN public.races.race_number IS 'R';
CREATE INDEX races_created_idx ON public.races (created_at DESC);
ALTER TABLE public.races ENABLE ROW LEVEL SECURITY;
CREATE POLICY races_read ON public.races FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY races_all ON public.races USING (race_number > 0) WITH CHECK (race_number > 0);
GRANT SELECT ON public.races TO anon;
GRANT UPDATE (race_number) ON public.races TO authenticated;
CREATE VIEW public.races_view WITH (security_invoker = true) AS
  SELECT race_id, venue_code FROM public.races;

CREATE FUNCTION public.race_count(p_venue text) RETURNS bigint
  LANGUAGE sql STABLE AS $$ SELECT count(*) FROM public.races WHERE venue_code = p_venue $$;
CREATE FUNCTION public.race_count(p_venue text, p_min int) RETURNS bigint
  LANGUAGE sql STABLE SECURITY DEFINER AS $$ SELECT count(*) FROM public.races WHERE venue_code = p_venue AND race_number >= p_min $$;
ALTER FUNCTION public.race_count(text, int) SET search_path = public, pg_temp;
REVOKE EXECUTE ON FUNCTION public.race_count(text, int) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.race_count(text, int) TO service_role;
`;

const db = new PGlite({ extensions: await loadTrgm() });
async function loadTrgm() {
  try {
    const { pg_trgm } = await import("@electric-sql/pglite/contrib/pg_trgm");
    return { pg_trgm };
  } catch {
    return {};
  }
}
let trgmLoaded = false;
try {
  await db.exec("CREATE EXTENSION pg_trgm");
  trgmLoaded = true;
} catch {
  // 拡張が読み込めない版の PGlite では、拡張の除外の確認だけを飛ばす
}
await db.exec(FIXTURE_SQL);

const raw = {};
for (const name of SNAPSHOT_QUERIES) {
  const sql = fs.readFileSync(path.join(QUERY_DIR, `${name}.sql`), "utf8");
  check(`${name}.sql は ro-query の受け付ける1文`, checkReadStatement(sql).ok);
  try {
    raw[name] = await runReadOnlyQuery(db, sql, {
      limit: MAX_ROW_LIMIT,
      expectedRole: "postgres",
    });
    check(`${name}.sql を PGlite で実行できる`, true);
  } catch (e) {
    check(`${name}.sql を PGlite で実行できる`, false, e.message);
  }
}
check(
  "問い合わせのファイルは SNAPSHOT_QUERIES と過不足なし",
  JSON.stringify(
    fs
      .readdirSync(QUERY_DIR)
      .filter((f) => f.endsWith(".sql"))
      .map((f) => f.replace(/\.sql$/, ""))
      .sort(),
  ) === JSON.stringify([...SNAPSHOT_QUERIES].sort()),
);

const snap = buildSnapshot(raw, {
  capturedAt: "2026-10-27T00:00:00.000Z",
  ledger: LEDGER,
});
const rel = (n) => snap.relations.find((r) => r.name === n);
const races = rel("races");
check(
  "表・ビューは名前の順で3つ（races・races_view・venues）",
  JSON.stringify(snap.relations.map((r) => `${r.name}:${r.kind}`)) ===
    JSON.stringify(["races:table", "races_view:view", "venues:table"]),
);
check(
  "counts",
  JSON.stringify(snap.counts) ===
    JSON.stringify({
      relations: 3,
      tables: 2,
      views: 1,
      columns: 9,
      functions: 2,
      policies: 2,
      constraints: 5,
      indexes: 4,
    }),
  JSON.stringify(snap.counts),
);
check(
  "RLS とコメント",
  races.rlsEnabled === true &&
    races.comment === "1行1レース" &&
    rel("venues").rlsEnabled === false,
);
check(
  "列は位置の順、型・NOT NULL・既定・identity・コメント",
  JSON.stringify(races.columns.map((c) => c.name)) ===
    JSON.stringify([
      "race_id",
      "venue_code",
      "race_number",
      "seq",
      "created_at",
    ]) &&
    races.columns[4].default === "now()" &&
    races.columns[4].type === "timestamp with time zone" &&
    races.columns[3].identity === "by_default" &&
    races.columns[0].identity === null &&
    races.columns[2].comment === "R" &&
    races.columns[1].notNull === true,
);
const fk = races.constraints.find((c) => c.type === "foreign_key");
check(
  "外部キーは参照先をスキーマつきで、定義に ON DELETE CASCADE",
  fk?.references === "public.venues" && /ON DELETE CASCADE/.test(fk.definition),
  JSON.stringify(fk),
);
check(
  "制約の種類（主キー・外部キー・CHECK・一意）",
  JSON.stringify(races.constraints.map((c) => c.type).sort()) ===
    JSON.stringify(["check", "foreign_key", "primary_key", "unique"]),
  JSON.stringify(races.constraints.map((c) => c.type)),
);
check(
  "索引: 主キー・一意・作った索引",
  races.indexes.some((i) => i.primary && i.unique) &&
    races.indexes.some(
      (i) => i.name === "races_created_idx" && /DESC/.test(i.definition),
    ),
);
const pRead = races.policies.find((p) => p.name === "races_read");
const pAll = races.policies.find((p) => p.name === "races_all");
check(
  "ポリシー: コマンド・ロール（PUBLIC を含む）・USING・WITH CHECK",
  pRead?.command === "SELECT" &&
    JSON.stringify(pRead.roles) === JSON.stringify(["anon", "authenticated"]) &&
    pAll?.command === "ALL" &&
    JSON.stringify(pAll.roles) === JSON.stringify(["PUBLIC"]) &&
    pAll.withCheck === "(race_number > 0)",
  JSON.stringify(races.policies),
);
check(
  "表の権限: anon の SELECT・service_role の既定の SELECT",
  races.grants.some(
    (g) => g.grantee === "anon" && g.privileges.join() === "SELECT",
  ) &&
    races.grants.some(
      (g) => g.grantee === "service_role" && g.privileges.join() === "SELECT",
    ),
  JSON.stringify(races.grants),
);
check(
  "列単位の権限は列に付く",
  JSON.stringify(races.columns[2].grants) ===
    JSON.stringify([
      { grantee: "authenticated", privileges: ["UPDATE"], grantable: [] },
    ]),
  JSON.stringify(races.columns[2].grants),
);
check(
  "ビューの定義は行の配列",
  Array.isArray(rel("races_view").viewDefinition) &&
    rel("races_view").viewDefinition.join("\n").includes("FROM races"),
);
const [f1, f2] = snap.functions;
check(
  "関数は名前と引数の型の順（同じ名前の2つ）",
  f1?.identityArgs === "p_venue text" &&
    f2?.identityArgs === "p_venue text, p_min integer",
  JSON.stringify(snap.functions.map((f) => f.identityArgs)),
);
check(
  "関数: ALTER した search_path が config と定義に出る、SECURITY DEFINER・volatility・md5",
  JSON.stringify(f2.config) ===
    JSON.stringify(["search_path=public, pg_temp"]) &&
    f2.definition.some((l) =>
      /SET search_path TO 'public', 'pg_temp'/.test(l),
    ) &&
    f2.securityDefiner === true &&
    f2.volatility === "stable" &&
    f1.config === null &&
    /^[0-9a-f]{32}$/.test(f1.prosrcMd5),
  JSON.stringify({ config: f2.config, def: f2.definition }),
);
check(
  "関数の権限: 既定は PUBLIC の EXECUTE、REVOKE したものは PUBLIC が無い",
  f1.grants.some(
    (g) => g.grantee === "PUBLIC" && g.privileges.join() === "EXECUTE",
  ) &&
    !f2.grants.some((g) => g.grantee === "PUBLIC") &&
    f2.grants.some((g) => g.grantee === "service_role"),
  JSON.stringify({ f1: f1.grants, f2: f2.grants }),
);
check(
  "シーケンス（identity）と既定の権限",
  snap.sequences.some((s) => s.name === "races_seq_seq") &&
    snap.defaultPrivileges.some(
      (d) =>
        d.objectType === "table" &&
        d.role === "postgres" &&
        d.grantee === "service_role",
    ),
  JSON.stringify({
    seq: snap.sequences.map((s) => s.name),
    def: snap.defaultPrivileges,
  }),
);
if (trgmLoaded) {
  check(
    "拡張の作った関数（pg_trgm）は入らない",
    !snap.functions.some((f) => /trgm|similarity/.test(f.name)),
  );
} else {
  console.log(
    "[SKIP] pg_trgm が PGlite で読み込めないので、拡張の除外の確認を飛ばす",
  );
}
check(
  "同じスキーマなら同じ出力（capturedAt 以外）",
  serializeSnapshot(
    buildSnapshot(raw, {
      capturedAt: "2026-10-27T00:00:00.000Z",
      ledger: LEDGER,
    }),
  ) === serializeSnapshot(snap),
);
check(
  "行数の目安（reltuples）を入れない",
  snap.relations.every(
    (r) => !Object.keys(r).some((k) => /tuple|estimate|rows/i.test(k)),
  ),
);

// ---------------------------------------------------------------------------
// (b) 組み立ての失敗
// ---------------------------------------------------------------------------
const opts = { capturedAt: "2026-10-27T00:00:00.000Z", ledger: LEDGER };
const withRows = (name, rows, extra = {}) => ({
  ...raw,
  [name]: { ...raw[name], rows, ...extra },
});
check(
  "打ち切り（truncated）は失敗",
  throwsWith(
    () =>
      buildSnapshot(
        withRows("columns", raw.columns.rows, { truncated: true }),
        opts,
      ),
    /打ち切られた/,
  ),
);
check(
  "truncated が無い（false でない）出力も失敗",
  throwsWith(
    () =>
      buildSnapshot(
        withRows("columns", raw.columns.rows, { truncated: undefined }),
        opts,
      ),
    /打ち切られた/,
  ),
);
check(
  "問い合わせの欠けは失敗",
  throwsWith(
    () => buildSnapshot({ ...raw, grants: undefined }, opts),
    /grants の結果が無い/,
  ),
);
check(
  "知らない relkind は失敗",
  throwsWith(
    () =>
      buildSnapshot(
        withRows("relations", [
          ...raw.relations.rows,
          { ...raw.relations.rows[0], name: "zz", relkind: "q" },
        ]),
        opts,
      ),
    /知らない relkind/,
  ),
);
check(
  "一覧に無い表の列は失敗",
  throwsWith(
    () =>
      buildSnapshot(
        withRows("columns", [
          ...raw.columns.rows,
          { ...raw.columns.rows[0], table_name: "ghost" },
        ]),
        opts,
      ),
    /列 の表 ghost/,
  ),
);
check(
  "一覧に無い関数の権限は失敗",
  throwsWith(
    () =>
      buildSnapshot(
        withRows("grants", [
          ...raw.grants.rows,
          {
            object_type: "function",
            name: "ghost",
            identity_args: "",
            grantee: "anon",
            privileges: ["EXECUTE"],
            grantable: null,
          },
        ]),
        opts,
      ),
    /関数の権限の ghost/,
  ),
);
check(
  "鍵らしい文字列（JWT）は失敗",
  throwsWith(
    () =>
      buildSnapshot(
        withRows(
          "relations",
          raw.relations.rows.map((r, i) =>
            i === 0
              ? {
                  ...r,
                  comment:
                    "eyJhbGciOiJIUzI1NiJ9.eyJyb2xlIjoic2VydmljZV9yb2xlIn0.x",
                }
              : r,
          ),
        ),
        opts,
      ),
    /鍵らしい文字列/,
  ),
);
check(
  "台帳に適用済みが無ければ失敗",
  throwsWith(
    () => buildSnapshot(raw, { ...opts, ledger: "" }),
    /適用済みの番号が無い/,
  ),
);

// ---------------------------------------------------------------------------
// (c) 台帳の読み方と鮮度
// ---------------------------------------------------------------------------
const state = appliedLedgerState(LEDGER);
check(
  "appliedThrough は適用済みの最大の番号、pendingAtCapture はそれ以下の適用済みでない番号（行の無い 3 も入る、番号なしの行は数えない）",
  state.appliedThrough === 6 &&
    JSON.stringify(state.pendingAtCapture) === JSON.stringify([2, 3, 5]),
  JSON.stringify(state),
);
check(
  "写しと同じ台帳なら古くない",
  snapshotFreshness(state, LEDGER).stale === false,
);
const later = LEDGER.replace(
  "| 008 | 008_h.sql | 未適用 |",
  "| 008 | 008_h.sql | 適用済み |",
);
check(
  "後の番号が適用済みになったら古い",
  JSON.stringify(snapshotFreshness(state, later)) ===
    JSON.stringify({
      stale: true,
      snapshotAppliedThrough: 6,
      ledgerAppliedThrough: 8,
      appliedSince: [8],
    }),
  JSON.stringify(snapshotFreshness(state, later)),
);
const backfilled = LEDGER.replace(
  "| 002 | 002_b.sql | 未適用（案） |",
  "| 002 | 002_b.sql | 適用済み |",
);
check(
  "取得の時に未適用だった小さい番号が後で適用済みになっても古い",
  JSON.stringify(snapshotFreshness(state, backfilled).appliedSince) === "[2]",
);
const addedRow = `${LEDGER}\n| 003 | 003_c.sql | 適用済み（db-apply が行を足した） | c |`;
check(
  "取得の時に台帳に行の無かった番号が後で適用済みで足されても古い",
  JSON.stringify(snapshotFreshness(state, addedRow).appliedSince) === "[3]",
);

// ---------------------------------------------------------------------------
// (d) コミット済みの写し
// ---------------------------------------------------------------------------
const snapshotPath = path.join(ROOT, SNAPSHOT_FILE);
if (!fs.existsSync(snapshotPath)) {
  check(`${SNAPSHOT_FILE} がある`, false);
} else {
  const text = fs.readFileSync(snapshotPath, "utf8");
  let committed = null;
  try {
    committed = JSON.parse(text);
  } catch (e) {
    check(`${SNAPSHOT_FILE} が JSON として読める`, false, e.message);
  }
  if (committed) {
    check(
      `${SNAPSHOT_FILE} は組み立ての出力の形のまま（手で書き換えていない）`,
      serializeSnapshot(committed) === text,
    );
    check(
      "format・capturedAt・appliedThrough",
      committed.format === SNAPSHOT_FORMAT &&
        !Number.isNaN(Date.parse(committed.capturedAt)) &&
        Number.isInteger(committed.appliedThrough) &&
        Array.isArray(committed.pendingAtCapture),
    );
    const rels = committed.relations ?? [];
    const fns = committed.functions ?? [];
    const sum = (k) => rels.reduce((a, r) => a + (r[k]?.length ?? 0), 0);
    check(
      "counts が中身と一致",
      committed.counts?.relations === rels.length &&
        committed.counts?.functions === fns.length &&
        committed.counts?.columns === sum("columns") &&
        committed.counts?.policies === sum("policies") &&
        committed.counts?.constraints === sum("constraints") &&
        committed.counts?.indexes === sum("indexes"),
      JSON.stringify(committed.counts),
    );
    check(
      "表・ビューは名前の順、関数は名前の順",
      rels.every((r, i) => i === 0 || rels[i - 1].name < r.name) &&
        fns.every((f, i) => i === 0 || fns[i - 1].name <= f.name),
    );
    const ledgerNow = appliedLedgerState(
      fs.readFileSync(path.join(ROOT, "docs/db-migration/APPLIED.md"), "utf8"),
    );
    check(
      "写しの appliedThrough は今の台帳の適用済みの最大以下",
      committed.appliedThrough <= (ledgerNow.appliedThrough ?? -1),
      `${committed.appliedThrough} > ${ledgerNow.appliedThrough}`,
    );
  }
}

await db.close();
if (failures > 0) {
  console.error(`\n${failures} 件の確認が失敗した`);
  process.exit(1);
}
console.log("\nOK: schema-snapshot");
