import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PGlite } from "@electric-sql/pglite";
import { pg_trgm } from "@electric-sql/pglite/contrib/pg_trgm";
import {
  checkReadStatement,
  runReadOnlyQuery,
  MAX_ROW_LIMIT,
} from "../lib/roQuery.js";
import {
  LEDGER_FILE,
  SNAPSHOT_FILE,
  SNAPSHOT_FORMAT,
  SNAPSHOT_QUERIES,
  appliedLedgerState,
  buildSnapshot,
  serializeSnapshot,
  snapshotRegression,
} from "../lib/schemaSnapshot.js";
import { runSchemaSnapshotScenes1 } from "./verifyData/schema-snapshot-scenes-1.js";
import { runSchemaSnapshotScenes2, runSchemaSnapshotScenes3 } from "./verifyData/schema-snapshot-scenes-2.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "../..");
const QUERY_DIR = path.join(ROOT, "scripts/db/schema-snapshot");

let failures = 0;
function check(label, pass, detail = "") {
  if (pass) console.log(`[OK] ${label}`);
  else {
    failures++;
    console.error(`[NG] ${label}${detail ? ` (${detail})` : ""}`);
  }
}
function throwsWith(fn, pattern) {
  try {
    fn();
    return false;
  } catch (e) {
    return pattern.test(e.message);
  }
}

const LEDGER = [
  "| 番号 | ファイル | 状況 | 内容 |",
  "|---|---|---|---|",
  "| 001 | 001_a.sql | 適用済み | a |",
  "| 002 | 002_b.sql | 未適用（案） | b |",
  "| 004 | 004_d.sql | 適用済み（2026-10-27） | d |",
  "| 004 | 004_d2.sql | 未適用 | 同じ番号の別のファイル |",
  "| 005 | 005_e.sql | 廃止（適用しない） | e |",
  "| 006 | 006_f.sql | 適用済み | f |",
  "| 013b | 013b_g.sql | 不明 | g |",
  "| 008 | 008_h.sql | 未適用 | h |",
  "| （番号なし） | x.sql | 適用済み | x |",
].join("\n");

// ---------------------------------------------------------------------------
// (a) PGlite で問い合わせを実行して組み立てる
// ---------------------------------------------------------------------------
const FIXTURE_SQL = `
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN BYPASSRLS;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public GRANT SELECT ON TABLES TO service_role;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres REVOKE ALL ON TYPES FROM PUBLIC, postgres;
CREATE EXTENSION pg_trgm;

CREATE TABLE public.venues (code text PRIMARY KEY, name text NOT NULL);
CREATE TABLE public.races (
  race_id text PRIMARY KEY,
  venue_code text NOT NULL,
  race_number int NOT NULL CHECK (race_number BETWEEN 1 AND 12),
  seq bigint GENERATED BY DEFAULT AS IDENTITY,
  serial_no serial,
  label text GENERATED ALWAYS AS (venue_code || '-' || race_number) STORED,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT races_venue_fk FOREIGN KEY (venue_code) REFERENCES public.venues(code) ON DELETE CASCADE,
  UNIQUE (venue_code, race_number)
);
COMMENT ON TABLE public.races IS '1行1レース';
COMMENT ON COLUMN public.races.race_number IS 'R';
CREATE INDEX races_created_idx ON public.races (created_at DESC);
ALTER TABLE public.races ENABLE ROW LEVEL SECURITY;
CREATE POLICY races_read ON public.races FOR SELECT TO authenticated, anon USING (true);
CREATE POLICY races_all ON public.races USING (race_number > 0) WITH CHECK (race_number > 0);
GRANT SELECT ON public.races TO anon;
GRANT UPDATE (race_number) ON public.races TO authenticated;
CREATE VIEW public.races_view WITH (security_invoker = true) AS
  SELECT race_id, venue_code FROM public.races;

CREATE FUNCTION public.race_count(p_venue text) RETURNS bigint
  LANGUAGE sql STABLE AS $$ SELECT count(*) FROM public.races WHERE venue_code = p_venue $$;
CREATE FUNCTION public.race_count(p_venue text, p_min int) RETURNS bigint
  LANGUAGE sql STABLE SECURITY DEFINER AS $$ SELECT count(*) FROM public.races WHERE venue_code = p_venue AND race_number >= p_min $$;
ALTER FUNCTION public.race_count(text, int) SET search_path = public, pg_temp;
GRANT EXECUTE ON FUNCTION public.race_count(text, int) TO service_role;
CREATE FUNCTION public.races_guard() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;
CREATE TRIGGER races_guard BEFORE UPDATE OF race_number ON public.races
  FOR EACH ROW EXECUTE FUNCTION public.races_guard();
`;

const db = new PGlite({ extensions: { pg_trgm } });
await db.exec(FIXTURE_SQL);

const raw = {};
for (const name of SNAPSHOT_QUERIES) {
  const sql = fs.readFileSync(path.join(QUERY_DIR, `${name}.sql`), "utf8");
  check(`${name}.sql は ro-query の受け付ける1文`, checkReadStatement(sql).ok);
  try {
    raw[name] = await runReadOnlyQuery(db, sql, {
      limit: MAX_ROW_LIMIT,
      expectedRole: "postgres",
    });
    check(`${name}.sql を PGlite で実行できる`, true);
  } catch (e) {
    check(`${name}.sql を PGlite で実行できる`, false, e.message);
  }
}
check(
  "問い合わせのファイルは SNAPSHOT_QUERIES と過不足なし",
  JSON.stringify(
    fs
      .readdirSync(QUERY_DIR)
      .filter((f) => f.endsWith(".sql"))
      .map((f) => f.replace(/\.sql$/, ""))
      .sort(),
  ) === JSON.stringify([...SNAPSHOT_QUERIES].sort()),
);

const opts = { capturedAt: "2026-10-27T00:00:00.000Z", ledger: LEDGER };
const snap = buildSnapshot(raw, opts);
const rel = (n) => snap.relations.find((r) => r.name === n);
const races = rel("races");
const col = (n) => races.columns.find((c) => c.name === n);
check(
  "表・ビューは名前の順で3つ（races・races_view・venues）",
  JSON.stringify(snap.relations.map((r) => `${r.name}:${r.kind}`)) ===
    JSON.stringify(["races:table", "races_view:view", "venues:table"]),
);
check(
  "counts",
  JSON.stringify(snap.counts) ===
    JSON.stringify({
      relations: 3,
      tables: 2,
      views: 1,
      columns: 11,
      functions: 3,
      policies: 2,
      constraints: 5,
      indexes: 4,
      triggers: 1,
    }),
  JSON.stringify(snap.counts),
);
check(
  "RLS とコメント",
  races.rlsEnabled === true &&
    races.comment === "1行1レース" &&
    rel("venues").rlsEnabled === false,
);
check(
  "列は位置の順、型・NOT NULL・既定・identity・生成列・serial・コメント",
  JSON.stringify(races.columns.map((c) => c.name)) ===
    JSON.stringify([
      "race_id",
      "venue_code",
      "race_number",
      "seq",
      "serial_no",
      "label",
      "created_at",
    ]) &&
    col("created_at").default === "now()" &&
    col("created_at").type === "timestamp with time zone" &&
    col("seq").identity === "by_default" &&
    col("race_id").identity === null &&
    col("label").generated === "stored" &&
    /nextval\('races_serial_no_seq'/.test(col("serial_no").default ?? "") &&
    col("race_number").comment === "R" &&
    col("venue_code").notNull === true,
  JSON.stringify(races.columns),
);
const fk = races.constraints.find((c) => c.type === "foreign_key");
check(
  "外部キーは参照先をスキーマつきで、列の対応つき、定義に ON DELETE CASCADE",
  fk?.references === "public.venues" &&
    JSON.stringify(fk.columns) === '["venue_code"]' &&
    JSON.stringify(fk.referencesColumns) === '["code"]' &&
    /ON DELETE CASCADE/.test(fk.definition),
  JSON.stringify(fk),
);
const uq = races.constraints.find((c) => c.type === "unique");
check(
  "一意の制約は列の順を保つ、外部キーでないものは referencesColumns が null",
  JSON.stringify(uq?.columns) === '["venue_code","race_number"]' &&
    uq.referencesColumns === null,
  JSON.stringify(uq),
);
check(
  "制約の種類（主キー・外部キー・CHECK・一意）。NOT NULL は入らない",
  JSON.stringify(races.constraints.map((c) => c.type).sort()) ===
    JSON.stringify(["check", "foreign_key", "primary_key", "unique"]),
  JSON.stringify(races.constraints.map((c) => c.type)),
);
check(
  "索引: 主キー・一意・作った索引",
  races.indexes.some((i) => i.primary && i.unique) &&
    races.indexes.some(
      (i) => i.name === "races_created_idx" && /DESC/.test(i.definition),
    ),
);
const pRead = races.policies.find((p) => p.name === "races_read");
const pAll = races.policies.find((p) => p.name === "races_all");
check(
  "ポリシー: コマンド・ロール（名前の順、PUBLIC を含む）・USING・WITH CHECK",
  pRead?.command === "SELECT" &&
    JSON.stringify(pRead.roles) === JSON.stringify(["anon", "authenticated"]) &&
    pAll?.command === "ALL" &&
    JSON.stringify(pAll.roles) === JSON.stringify(["PUBLIC"]) &&
    pAll.withCheck === "(race_number > 0)",
  JSON.stringify(races.policies),
);
const trg = races.triggers[0];
check(
  "トリガー: 表・関数・定義（操作と列）・有効",
  trg?.name === "races_guard" &&
    trg.function === "public.races_guard()" &&
    trg.enabled === "origin" &&
    /BEFORE UPDATE OF race_number ON (public\.)?races/.test(trg.definition),
  JSON.stringify(races.triggers),
);
check(
  "表の権限: anon の SELECT・service_role の既定の SELECT",
  races.grants.some(
    (g) => g.grantee === "anon" && g.privileges.join() === "SELECT",
  ) &&
    races.grants.some(
      (g) => g.grantee === "service_role" && g.privileges.join() === "SELECT",
    ),
  JSON.stringify(races.grants),
);
check(
  "列単位の権限は列に付く",
  JSON.stringify(col("race_number").grants) ===
    JSON.stringify([
      { grantee: "authenticated", privileges: ["UPDATE"], grantable: [] },
    ]),
  JSON.stringify(col("race_number").grants),
);
check(
  "ビューの定義は行の配列",
  Array.isArray(rel("races_view").viewDefinition) &&
    rel("races_view").viewDefinition.join("\n").includes("FROM races"),
);
const fns = snap.functions;
check(
  "関数は名前と引数の型の順（同じ名前の2つ）",
  JSON.stringify(fns.map((f) => `${f.name}(${f.identityArgs})`)) ===
    JSON.stringify([
      "race_count(p_venue text)",
      "race_count(p_venue text, p_min integer)",
      "races_guard()",
    ]),
  JSON.stringify(fns.map((f) => f.identityArgs)),
);
const [f1, f2] = fns;

// ---- 後半の場面（verifyData/schema-snapshot-scenes-1.js・schema-snapshot-scenes-2.js） ----
await runSchemaSnapshotScenes1({ check, throwsWith, LEDGER, db, raw, opts, snap, fns, f2, f1 });
runSchemaSnapshotScenes2({ check, LEDGER, db, snap });

// ---------------------------------------------------------------------------
// (d) コミット済みの写し
// ---------------------------------------------------------------------------
const baseArg = process.argv
  .slice(2)
  .filter((a) => a.startsWith("--base="))
  .map((a) => a.slice("--base=".length))
  .pop();
const base = baseArg || "origin/master";

function readBaseSnapshot() {
  const git = (args) =>
    execFileSync("git", args, {
      cwd: ROOT,
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
      stdio: ["ignore", "pipe", "ignore"],
    });
  let ref = base;
  try {
    const baseSha = git([
      "rev-parse",
      "--verify",
      "--quiet",
      `${base}^{commit}`,
    ]).trim();
    const headSha = git(["rev-parse", "HEAD"]).trim();
    // master への push の実行では base が HEAD そのもの。自分と比べても意味が無いので、直前の master（第1の親）と比べる
    if (baseSha === headSha) ref = "HEAD^1";
  } catch {
    return { skip: `base（${base}）が無い` };
  }
  try {
    return {
      ref,
      snapshot: JSON.parse(git(["show", `${ref}:${SNAPSHOT_FILE}`])),
    };
  } catch {
    return { ref, snapshot: null }; // base にまだ写しが無い（最初の PR）
  }
}

const snapshotPath = path.join(ROOT, SNAPSHOT_FILE);
if (!fs.existsSync(snapshotPath)) {
  check(`${SNAPSHOT_FILE} がある`, false);
} else {
  const text = fs.readFileSync(snapshotPath, "utf8");
  let committed = null;
  try {
    committed = JSON.parse(text);
  } catch (e) {
    check(`${SNAPSHOT_FILE} が JSON として読める`, false, e.message);
  }
  if (committed) {
    check(
      `${SNAPSHOT_FILE} は整形のまま（serializeSnapshot で書き直しても変わらない）`,
      serializeSnapshot(committed) === text,
    );
    check(
      "format・capturedAt・appliedThrough・appliedFilesAtCapture",
      committed.format === SNAPSHOT_FORMAT &&
        !Number.isNaN(Date.parse(committed.capturedAt)) &&
        Number.isInteger(committed.appliedThrough) &&
        Array.isArray(committed.appliedFilesAtCapture) &&
        committed.appliedFilesAtCapture.length > 0,
    );
    const rels = committed.relations ?? [];
    const cfns = committed.functions ?? [];
    const sum = (k) => rels.reduce((a, r) => a + (r[k]?.length ?? 0), 0);
    check(
      "counts が中身と一致",
      committed.counts?.relations === rels.length &&
        committed.counts?.functions === cfns.length &&
        committed.counts?.columns === sum("columns") &&
        committed.counts?.policies === sum("policies") &&
        committed.counts?.constraints === sum("constraints") &&
        committed.counts?.indexes === sum("indexes") &&
        committed.counts?.triggers === sum("triggers"),
      JSON.stringify(committed.counts),
    );
    const sortedBy = (list, key) =>
      list.every((x, i) => i === 0 || key(list[i - 1]) <= key(x));
    check(
      "並び: 表・関数・各表の列・制約・索引・ポリシー・トリガー・権限",
      sortedBy(rels, (r) => r.name) &&
        sortedBy(cfns, (f) => `${f.name}\u0000${f.identityArgs}`) &&
        rels.every(
          (r) =>
            sortedBy(r.columns, (c) => String(c.position).padStart(5, "0")) &&
            ["constraints", "indexes", "policies", "triggers"].every((k) =>
              sortedBy(r[k], (x) => x.name),
            ) &&
            sortedBy(r.grants, (g) => g.grantee),
        ),
    );
    const ledgerNow = appliedLedgerState(
      fs.readFileSync(path.join(ROOT, LEDGER_FILE), "utf8"),
    );
    check(
      "写しの appliedThrough は今の台帳の適用済みの最大以下",
      committed.appliedThrough <= (ledgerNow.appliedThrough ?? -1),
      `${committed.appliedThrough} > ${ledgerNow.appliedThrough}`,
    );
    const b = readBaseSnapshot();
    if (b.skip) {
      if (process.env.CI) check(`base の写しと比べる`, false, b.skip);
      else console.log(`[SKIP] base の写しとの比較（${b.skip}。CI では失敗）`);
    } else {
      const reason =
        b.snapshot && b.snapshot.format === SNAPSHOT_FORMAT
          ? snapshotRegression(committed, b.snapshot)
          : null;
      check(
        `base（${b.ref}）の写しより前の取得に戻っていない`,
        reason === null,
        reason ?? "",
      );
    }
  }
}

// ---- 後半の場面（verifyData/schema-snapshot-scenes-2.js） ----
await runSchemaSnapshotScenes3({ check, LEDGER, db, snap });
if (failures > 0) {
  console.error(`\n${failures} 件の確認が失敗した`);
  process.exit(1);
}
console.log("\nOK: schema-snapshot");
