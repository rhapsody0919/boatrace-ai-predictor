/**
 * verify-meet-start-date.js — 会場単位の「節の初日」の判定の回帰テスト（BOA-508）。
 *
 * `src/utils/meetGrouping.js` の `findMeetStartDate` は、レース詳細の今節タブが
 * 「どこからが今の節か」を決めるのに使う。ここを誤ると、得点率そのものは正しくても
 * **節内順位・出場人数・準優の目安・必要得点が前の節の値になる**。
 *
 * 旧実装（`getMeetScoreboard` にあった日付ヒューリスティックのインライン複製）は
 * 「間が2日を**超えたら**別の節」だったため、節と節の間が中1日空くと
 * 連続する開催日の差がちょうど2日になって境目とみなされず、**前の節が丸ごと
 * 混ざっていた**（BOA-491: 2026-09-28 戸田8Rで節内順位が6艇とも「対象外」、
 * 順位の対象が41人・準優の目安5.63が前の節の値になった）。
 *
 * 判定に使う根拠は強い順に3つ。
 *   1. 前の日が `is_final_day`     … いちばん強い。増減にも空きにも左右されない
 *   2. `series_day` が1、または減った … 節の頭
 *   3. 前の開催日から2日以上空いた   … 実測で偽の空きは0件なので、条件を絞らない
 *
 * 日付・`series_day`・`is_final_day` の並びは**すべて本番DBに実在したもの**
 * （戸田02・住之江12 は 2026-09 の実測をそのまま写している）。実Supabaseへは
 * 接続しないので tier=ci。実データ全件との突き合わせは `verify-meet-grouping.js`
 * （tier=manual）が担う。
 */
import { findMeetStartDate } from "../../src/utils/meetGrouping.js";

let failures = 0;
function check(label, actual, expected) {
  const a = JSON.stringify(actual);
  const e = JSON.stringify(expected);
  if (a === e) {
    console.log(`✅ ${label}`);
  } else {
    failures += 1;
    console.error(`❌ ${label}: expected ${e}, got ${a}`);
  }
}

/**
 * `[["2026-09-19", 2, false], ...]` を入力の形にする。
 * `seriesDay` / `isFinalDay` の null は「種別が取れていない」を表す
 */
const days = (rows) =>
  rows.map(([date, seriesDay, isFinalDay = false]) => ({
    date,
    seriesDay,
    isFinalDay,
  }));

// ---- 1. 中1日の休みを挟む（BOA-491 の実データ） -------------------------------
// 戸田02 2026-09-19〜09-28 の**実測そのまま**。09-19 は節の途中（初日の行が窓の
// 外）で series_day=2、09-21→09-22 は中止順延で 4 が2日続き、09-23→09-24 は 5→7 で
// 飛んでいる。09-24 が最終日、09-25 は開催なし、09-26 から今の節。
// 旧実装は 09-28 を開くと 09-19 まで遡っていた
const TODA = days([
  ["2026-09-19", 2],
  ["2026-09-20", 3],
  ["2026-09-21", 4],
  ["2026-09-22", 4], // 順延で同値のまま
  ["2026-09-23", 5],
  ["2026-09-24", 7, true], // 飛び（5→7）かつ最終日
  ["2026-09-26", 1],
  ["2026-09-27", 2],
  ["2026-09-28", 3],
]);
check(
  "中1日の休みで節が切れる（戸田 2026-09-28）",
  findMeetStartDate(TODA, "2026-09-28"),
  "2026-09-26",
);
check(
  "同じ節の初日を開いても自分自身",
  findMeetStartDate(TODA, "2026-09-26"),
  "2026-09-26",
);
check(
  "前の節の日を開けば前の節の初日",
  findMeetStartDate(TODA, "2026-09-22"),
  "2026-09-19",
);

// 住之江12 2026-09-11〜09-20 の実測そのまま。09-16 が最終日、09-17 は開催なし。
// 旧実装は 09-20 を開くと 09-11 まで遡った
const SUMINOE = days([
  ["2026-09-11", 1],
  ["2026-09-12", 2],
  ["2026-09-13", 3],
  ["2026-09-14", 4],
  ["2026-09-15", 5],
  ["2026-09-16", 6, true],
  ["2026-09-18", 1],
  ["2026-09-19", 2],
  ["2026-09-20", 3],
]);
check(
  "中1日の休みで節が切れる（住之江 2026-09-20）",
  findMeetStartDate(SUMINOE, "2026-09-20"),
  "2026-09-18",
);

// ---- 2. is_final_day がいちばん強い根拠 ---------------------------------------
// `series_day` が増え続けていても、前の日が最終日ならそこが境目。
// 次の節の初日の行が無く series_day=3 から始まるようなとき、series_day だけでは
// 「同じ節の続き」と読めてしまう（自己レビュー修正 25ee0bb2 が作った取り逃し経路）
check(
  "前の日が最終日なら、series_day が増えていても節が切れる",
  findMeetStartDate(
    days([
      ["2026-05-01", 1],
      ["2026-05-02", 2, true], // 最終日
      ["2026-05-04", 3], // 次の節（初日・2日目の行が無い）
      ["2026-05-05", 4],
    ]),
    "2026-05-05",
  ),
  "2026-05-04",
);
check(
  "前の日が最終日なら、日付が連続していても節が切れる",
  findMeetStartDate(
    days([
      ["2026-05-01", 5],
      ["2026-05-02", 6, true],
      ["2026-05-03", 7], // 休み無しで次の節（実データでは0件だが論理上ありうる）
    ]),
    "2026-05-03",
  ),
  "2026-05-03",
);

// ---- 3. 順延（series_day が同値で続く／飛ぶ） ---------------------------------
// 中止順延で series_day が同じ値のまま進む実例が3箇所ある（江戸川09-21→22、
// 戸田09-21→22、津09-22→23）。前後に同じ顔ぶれが出ているので同じ節の続き
check(
  "順延で series_day が同値のまま続いても節は切れない",
  findMeetStartDate(
    days([
      ["2026-09-19", 1],
      ["2026-09-20", 2],
      ["2026-09-21", 4],
      ["2026-09-22", 4],
      ["2026-09-23", 5],
    ]),
    "2026-09-23",
  ),
  "2026-09-19",
);
check(
  "順延で series_day が飛んでも節は切れない（5→7）",
  findMeetStartDate(
    days([
      ["2026-09-19", 1],
      ["2026-09-20", 5],
      ["2026-09-21", 7],
    ]),
    "2026-09-21",
  ),
  "2026-09-19",
);

// ---- 4. 初日の行が無い節 -------------------------------------------------------
// races ごと欠けていて series_day=2 から始まる実例がある（2026-06-04 江戸川・蒲郡）
check(
  "series_day が前の値より小さければ新しい節（初日の行が無い）",
  findMeetStartDate(
    days([
      ["2026-06-01", 5],
      ["2026-06-02", 6],
      ["2026-06-03", 7],
      ["2026-06-04", 2],
      ["2026-06-05", 3],
    ]),
    "2026-06-05",
  ),
  "2026-06-04",
);

// ---- 5. series_day が無くても壊れない（BOA-501 の想定） ------------------------
// series_day が埋まらない期間があるため、日付の連続性をフォールバックに残してある。
// 実測では、series_day を全部 null にしても 3,065（会場×日）すべてで答えが同じだった
check(
  "series_day も is_final_day も全て無くても、中1日の休みで節が切れる",
  findMeetStartDate(
    TODA.map((d) => ({ date: d.date, seriesDay: null, isFinalDay: null })),
    "2026-09-28",
  ),
  "2026-09-26",
);
check(
  "series_day が当日だけ無くても答えは変わらない（取得前の当日）",
  findMeetStartDate(
    TODA.map((d) =>
      d.date === "2026-09-28"
        ? { date: d.date, seriesDay: null, isFinalDay: null }
        : d,
    ),
    "2026-09-28",
  ),
  "2026-09-26",
);
// 実データに14箇所ある形。前の日は種別が取れていて、当日だけ取れていない
check(
  "片側（当日）だけ series_day が無くても、前の日が最終日なら切れる",
  findMeetStartDate(
    days([
      ["2026-09-23", 5],
      ["2026-09-24", 7, true],
      ["2026-09-26", null, null],
    ]),
    "2026-09-26",
  ),
  "2026-09-26",
);
// 逆向き。当日は取れていて、前の日が取れていない
check(
  "片側（前の日）だけ series_day が無くても、当日が series_day=1 なら切れる",
  findMeetStartDate(
    days([
      ["2026-09-23", null, null],
      ["2026-09-24", null, null],
      ["2026-09-26", 1],
    ]),
    "2026-09-26",
  ),
  "2026-09-26",
);

// ---- 5b. 空き2日以上は、他の根拠の有無に関わらず節の境目 -----------------------
// `findMeetStartDate` には**出走表にある日付**を渡す。1日ぶん未取得だと偽の
// 「空き」ができるので、一度は「前の日の種別が取れているときは空きを見ない」と
// 絞った（`25ee0bb2`）。だが本番の出走表46,944レース・会場×日3,913で数え直すと、
// 空き2日以上は688箇所あり
//   - 550箇所は節の境目と確認できる
//   - **「節の続きなのに空いている」は0件**
//   - 138箇所は `race_conditions` 未収録期間（2025-12〜2026-01）で判断材料が無い
// だった。絞ると138箇所と、`is_final_day` が立っていない境目3箇所で節を跨ぐ。
// 偽の空きは実データに存在しないので、条件を絞らずに使う
check(
  "空き2日以上なら、series_day が増えていても切る（偽の空きは実データに0件）",
  findMeetStartDate(
    days([
      ["2026-09-19", 1],
      ["2026-09-20", 2],
      ["2026-09-22", 4],
      ["2026-09-23", 5],
    ]),
    "2026-09-23",
  ),
  "2026-09-22",
);
// `race_conditions` 未収録期間（138箇所）の形。種別が1行も無いので空きだけが根拠
check(
  "種別が全く無い期間でも、空きで節が切れる",
  findMeetStartDate(
    days([
      ["2025-12-19", null, null],
      ["2025-12-20", null, null],
      ["2025-12-24", null, null],
      ["2025-12-25", null, null],
    ]),
    "2025-12-25",
  ),
  "2025-12-24",
);
// `is_final_day` が立っていない境目（実データに3箇所）。前の日は種別が取れていて
// F=false、次の日は series_day=1。ここで「種別が取れているから空きは見ない」と
// すると節を跨ぐ（津 2026-07-29 → 2026-08-05、住之江 2026-05-16 → 2026-05-22）
check(
  "前の日に is_final_day が立っていない境目でも、空きと series_day=1 で切れる",
  findMeetStartDate(
    days([
      ["2026-05-15", 1],
      ["2026-05-16", 2, false], // 実際はここが最終日だが印が無い
      ["2026-05-22", 1],
      ["2026-05-23", 2],
    ]),
    "2026-05-23",
  ),
  "2026-05-22",
);
// `isFinalDay` を渡さない古い呼び出し形（`{date, seriesDay}` のみ）でも、
// series_day と空きのフォールバックで従来どおり動く
check(
  "isFinalDay を渡さない呼び出しでも壊れない",
  findMeetStartDate(
    [
      { date: "2026-09-24", seriesDay: 7 },
      { date: "2026-09-26", seriesDay: 1 },
      { date: "2026-09-27", seriesDay: 2 },
    ],
    "2026-09-27",
  ),
  "2026-09-26",
);

// ---- 6. 境界・異常系 -----------------------------------------------------------
check("空の入力は null", findMeetStartDate([], "2026-09-28"), null);
check("配列でなければ null", findMeetStartDate(null, "2026-09-28"), null);
check(
  "表示日の行が無くても、それ以前で最後に見た節の初日を返す",
  findMeetStartDate(TODA, "2026-09-25"),
  "2026-09-19",
);
check(
  "窓の中が1つの節だけなら、その初日",
  findMeetStartDate(
    days([
      ["2026-09-26", 1],
      ["2026-09-27", 2],
    ]),
    "2026-09-27",
  ),
  "2026-09-26",
);
check(
  "窓が節の途中から始まっていても、窓の先頭を初日として返す",
  findMeetStartDate(
    days([
      ["2026-09-20", 3],
      ["2026-09-21", 4],
    ]),
    "2026-09-21",
  ),
  "2026-09-20",
);
check(
  "入力が日付順でなくても結果は同じ",
  findMeetStartDate([...TODA].reverse(), "2026-09-28"),
  "2026-09-26",
);

console.log(failures === 0 ? "\n全件パス" : `\n失敗 ${failures} 件`);
process.exit(failures === 0 ? 0 : 1);
