/**
 * verify-meet-start-date.js — 会場単位の「節の初日」の判定の回帰テスト（BOA-508）。
 *
 * `src/utils/meetGrouping.js` の `findMeetStartDate` は、レース詳細の今節タブが
 * 「どこからが今の節か」を決めるのに使う。ここを誤ると、得点率そのものは正しくても
 * **節内順位・出場人数・準優の目安・必要得点が前の節の値になる**。
 *
 * 旧実装（`getMeetScoreboard` にあった日付ヒューリスティックのインライン複製）は
 * 「間が2日を**超えたら**別の節」だったため、節と節の間が中1日空くと
 * 連続する開催日の差がちょうど2日になって境目とみなされず、**前の節が丸ごと
 * 混ざっていた**（BOA-491: 2026-09-28 戸田8Rで節内順位が6艇とも「対象外」、
 * 出場人数41人・準優の目安5.88が前の節の値になった）。
 *
 * ここで使う日付・`series_day` の並びは**すべて本番DBに実在したもの**。
 * 実Supabaseへは接続しないので tier=ci。実データ全件との突き合わせは
 * `verify-meet-grouping.js`（tier=manual）が担う。
 */
import { findMeetStartDate } from "../../src/utils/meetGrouping.js";

let failures = 0;
function check(label, actual, expected) {
  const a = JSON.stringify(actual);
  const e = JSON.stringify(expected);
  if (a === e) {
    console.log(`✅ ${label}`);
  } else {
    failures += 1;
    console.error(`❌ ${label}: expected ${e}, got ${a}`);
  }
}

/** `[["2026-09-19", 1], ...]` を入力の形にする（null は series_day 未取得） */
const days = (pairs) => pairs.map(([date, seriesDay]) => ({ date, seriesDay }));

// ---- 1. 中1日の休みを挟む（BOA-491 の実データ） -------------------------------
// 戸田: 09-19〜09-24 が前の節（09-24 が最終日・series_day=7）、09-25 は開催なし、
// 09-26〜09-28 が今の節。旧実装は 09-19 まで遡っていた
const TODA = days([
  ["2026-09-19", 2],
  ["2026-09-20", 3],
  ["2026-09-21", 4],
  ["2026-09-22", 5],
  ["2026-09-23", 6],
  ["2026-09-24", 7],
  ["2026-09-26", 1],
  ["2026-09-27", 2],
  ["2026-09-28", 3],
]);
check(
  "中1日の休みで節が切れる（戸田 2026-09-28）",
  findMeetStartDate(TODA, "2026-09-28"),
  "2026-09-26",
);
check(
  "同じ節の初日を開いても自分自身",
  findMeetStartDate(TODA, "2026-09-26"),
  "2026-09-26",
);
check(
  "前の節の日を開けば前の節の初日",
  findMeetStartDate(TODA, "2026-09-22"),
  "2026-09-19",
);

// 住之江: 09-11〜09-16 と 09-18〜09-23。旧実装は 09-20 を開くと 09-11 まで遡った
const SUMINOE = days([
  ["2026-09-11", 1],
  ["2026-09-12", 2],
  ["2026-09-13", 3],
  ["2026-09-14", 4],
  ["2026-09-15", 5],
  ["2026-09-16", 6],
  ["2026-09-18", 1],
  ["2026-09-19", 2],
  ["2026-09-20", 3],
]);
check(
  "中1日の休みで節が切れる（住之江 2026-09-20）",
  findMeetStartDate(SUMINOE, "2026-09-20"),
  "2026-09-18",
);

// ---- 2. 順延（series_day が同値で続く／飛ぶ） ---------------------------------
// 中止順延で series_day が同じ値のまま進む実例が3箇所ある（江戸川09-21→22、
// 戸田09-21→22、津09-22→23）。前後に同じ顔ぶれが出ているので同じ節の続き
check(
  "順延で series_day が同値のまま続いても節は切れない",
  findMeetStartDate(
    days([
      ["2026-09-19", 1],
      ["2026-09-20", 2],
      ["2026-09-21", 4],
      ["2026-09-22", 4],
      ["2026-09-23", 5],
    ]),
    "2026-09-23",
  ),
  "2026-09-19",
);
check(
  "順延で series_day が飛んでも節は切れない（5→7）",
  findMeetStartDate(
    days([
      ["2026-09-19", 1],
      ["2026-09-20", 5],
      ["2026-09-21", 7],
    ]),
    "2026-09-21",
  ),
  "2026-09-19",
);

// ---- 3. 初日の行が無い節 -------------------------------------------------------
// races ごと欠けていて series_day=2 から始まる実例がある（2026-06-04 江戸川・蒲郡）
check(
  "series_day が前の値より小さければ新しい節（初日の行が無い）",
  findMeetStartDate(
    days([
      ["2026-06-01", 5],
      ["2026-06-02", 6],
      ["2026-06-03", 7],
      ["2026-06-04", 2],
      ["2026-06-05", 3],
    ]),
    "2026-06-05",
  ),
  "2026-06-04",
);

// ---- 4. series_day が無くても壊れない（BOA-501 の想定） ------------------------
// series_day が埋まらない期間があるため、日付の連続性をフォールバックに残してある。
// 実測では、series_day を全部 null にしても 3,065（会場×日）すべてで答えが同じだった
check(
  "series_day が全て無くても、中1日の休みで節が切れる",
  findMeetStartDate(
    TODA.map((d) => ({ date: d.date, seriesDay: null })),
    "2026-09-28",
  ),
  "2026-09-26",
);
check(
  "series_day が当日だけ無くても答えは変わらない（取得前の当日）",
  findMeetStartDate(
    TODA.map((d) =>
      d.date === "2026-09-28" ? { date: d.date, seriesDay: null } : d,
    ),
    "2026-09-28",
  ),
  "2026-09-26",
);

// ---- 4b. 出走表が1日欠けても、series_day が続きと言うなら切らない ---------------
// `findMeetStartDate` には**出走表にある日付**を渡す。その日の出走表が未取得だと
// 偽の「空き」ができる。日付の空きを優先すると節の途中で切れるので、
// `series_day` が両側にあるときはそちらを優先する（旧実装は間2日まで許容していた
// ので、空き優先にすると許容がむしろ狭くなってしまう）
check(
  "節の途中で1日ぶん欠けても、series_day が続きなら切らない",
  findMeetStartDate(
    days([
      ["2026-09-19", 1],
      ["2026-09-20", 2],
      // 2026-09-21 の出走表が未取得（series_day は続いている）
      ["2026-09-22", 4],
      ["2026-09-23", 5],
    ]),
    "2026-09-23",
  ),
  "2026-09-19",
);
check(
  "1日欠けたうえ series_day も無ければ、空きで切る（判断材料が無いため）",
  findMeetStartDate(
    days([
      ["2026-09-19", null],
      ["2026-09-20", null],
      ["2026-09-22", null],
      ["2026-09-23", null],
    ]),
    "2026-09-23",
  ),
  "2026-09-22",
);

// ---- 5. 境界・異常系 -----------------------------------------------------------
check("空の入力は null", findMeetStartDate([], "2026-09-28"), null);
check("配列でなければ null", findMeetStartDate(null, "2026-09-28"), null);
check(
  "表示日の行が無くても、それ以前で最後に見た節の初日を返す",
  findMeetStartDate(TODA, "2026-09-25"),
  "2026-09-19",
);
check(
  "窓の中が1つの節だけなら、その初日",
  findMeetStartDate(
    days([
      ["2026-09-26", 1],
      ["2026-09-27", 2],
    ]),
    "2026-09-27",
  ),
  "2026-09-26",
);
check(
  "窓が節の途中から始まっていても、窓の先頭を初日として返す",
  findMeetStartDate(
    days([
      ["2026-09-20", 3],
      ["2026-09-21", 4],
    ]),
    "2026-09-21",
  ),
  "2026-09-20",
);
check(
  "入力が日付順でなくても結果は同じ",
  findMeetStartDate([...TODA].reverse(), "2026-09-28"),
  "2026-09-26",
);

console.log(failures === 0 ? "\n全件パス" : `\n失敗 ${failures} 件`);
process.exit(failures === 0 ? 0 : 1);
