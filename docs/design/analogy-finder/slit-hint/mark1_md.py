def c(x):
    k, n = x
    if n == 0: return '–'
    p, lo, hi = wilson(k, n)
    return f'{p:.3f} [{lo:.3f}–{hi:.3f}] {k}/{n}'
def s(x):
    k, n = x
    return '–' if n == 0 else f'{k/n:.3f} ({k}/{n})'
