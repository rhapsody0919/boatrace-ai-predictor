/**
 * 展示タイムの推移グラフの縦軸の範囲（BOA-557）。
 *
 * `["dataMin - 0.1", "dataMax + 0.1"]` だと端がデータ次第の半端な値になり、
 * 目盛りが 6.43 / 6.63 / … / 7.14 と読みにくい。端を 0.2 秒の倍数にそろえて、
 * 目盛りを 6.40 / 6.60 / 6.80 … と等間隔のきりの良い値にする。0.1 秒単位だと
 * 上端だけ 7.10 のように間隔が崩れた（上下 0.05 秒以上の余白は残す）。
 */
export const EXHIBITION_TIME_DOMAIN = [
  (min) => Math.floor((min - 0.05) * 5) / 5,
  (max) => Math.ceil((max + 0.05) * 5) / 5,
];
