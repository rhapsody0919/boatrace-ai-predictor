/**
 * 元の faqs に差し替えを重ねた写し（元は変えない）。差し替えのキーが元に無ければ投げる
 * @param {{category: string, questions: {q: string, a: string, link?: object}[]}[]} faqs
 */
export function applyFaqOverrides(faqs) {
  const known = new Set(faqs.flatMap((c) => c.questions.map((x) => x.q)));
  const missing = Object.keys(QUESTION_OVERRIDES).filter((q) => !known.has(q));
  if (missing.length > 0) {
    throw new Error(
      `faqInCaution: 元の FAQ に無い問いを差し替えようとしています: ${missing.join("／")}`,
    );
  }
  return faqs.map((c) => ({
    category: CATEGORY_RENAMES[c.category] ?? c.category,
    questions: c.questions.flatMap((x) => {
      if (!(x.q in QUESTION_OVERRIDES)) return [x];
      const next = QUESTION_OVERRIDES[x.q];
      return next === null ? [] : [next];
    }),
  }));
}
